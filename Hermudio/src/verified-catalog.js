/** 按场景(morning/afternoon/evening/night)筛选，命中不足则用全量兜底 */
function getSongsForScene(timeOfDay) {
  if (!timeOfDay) return VERIFIED_SONGS.slice();
  const matched = VERIFIED_SONGS.filter(s => s.scenes.includes(timeOfDay));
  return matched.length >= 3 ? matched : VERIFIED_SONGS.slice();
}

// 粗粒度的曲风能量分类，用于"安静点/热闹点"这类心情指令。
// 目录规模小（32首），按 style 字段分桶已经够用，不单独建标签体系。
const QUIET_STYLES = ['民谣', '民谣流行'];
const ENERGETIC_STYLES = ['摇滚', '独立摇滚'];

/** 按心情('quiet'|'energetic')筛选，命中不足则并入中性曲风兜底 */
function getSongsForMood(mood, timeOfDay) {
  const base = getSongsForScene(timeOfDay);
  if (mood !== 'quiet' && mood !== 'energetic') return base;
  const targetStyles = mood === 'quiet' ? QUIET_STYLES : ENERGETIC_STYLES;
  const matched = base.filter(s => targetStyles.includes(s.style));
  if (matched.length >= 4) return matched;
  // 命中不足时，从全量目录（不限场景）里补齐，保证换一批时够用
  const fromAll = VERIFIED_SONGS.filter(s => targetStyles.includes(s.style));
  return fromAll.length >= 4 ? fromAll : VERIFIED_SONGS.slice();
}

